#!/usr/bin/env python3
"""Generate tokens.css and a Tailwind mapping from replica-design tokens.json.
Standard library only.

    python3 build_tokens.py replica/design/tokens.json            # Tailwind v3 (tailwind.tokens.js)
    python3 build_tokens.py replica/design/tokens.json --tailwind4 # adds an @theme block to tokens.css
    python3 build_tokens.py tokens.json --out some/dir
    python3 build_tokens.py tokens.json --oklch                   # colours as oklch(), hex in a comment

"theme-default": "dark" in tokens.json makes :root dark whatever the OS says,
with light only under [data-theme="light"]. "type-ar" (any "type-xx") writes
that language's sizes and line heights under :lang(xx).

Outputs next to tokens.json (or --out):
  tokens.css          :root light vars, dark via prefers-color-scheme and
                      [data-theme="dark"], explicit [data-theme="light"] override
  tailwind.tokens.js  module.exports = { theme: { extend: {...} } } using var(--...)
                      (v3 only; v4 reads the @theme block in tokens.css)

Components then use classes like bg-surface text-text-muted rounded-md p-4.
"""

import argparse
import json
import math
import os
import sys


def oklch(hexv):
    """sRGB hex -> CSS oklch() (Ottosson OKLab). Keeps hex in a comment for readers."""
    h = hexv.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    alpha = int(h[6:8], 16) / 255.0 if len(h) == 8 else None
    def lin(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(int(h[i:i + 2], 16)) for i in (0, 2, 4))
    lm = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    mm = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    sm = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    L = 0.2104542553 * lm + 0.7936177850 * mm - 0.0040720468 * sm
    A = 1.9779984951 * lm - 2.4285922050 * mm + 0.4505937099 * sm
    B = 0.0259040371 * lm + 0.7827717662 * mm - 0.8086757660 * sm
    C = (A * A + B * B) ** 0.5
    H = (math.degrees(math.atan2(B, A)) + 360) % 360 if C > 0.0005 else 0.0
    if alpha is not None:
        return "oklch(%.1f%% %.3f %.1f / %.2f)" % (L * 100, C if C > 0.0005 else 0, H, alpha)
    return "oklch(%.1f%% %.3f %.1f)" % (L * 100, C if C > 0.0005 else 0, H)


def px(v):
    return "%spx" % v if isinstance(v, (int, float)) and v != 0 else str(v)


FORMAT = {"oklch": False}


def color_block(colors, indent="  "):
    if FORMAT["oklch"]:
        return "\n".join("%s--color-%s: %s; /* %s */" % (indent, k, oklch(v), v) for k, v in colors.items())
    return "\n".join("%s--color-%s: %s;" % (indent, k, v) for k, v in colors.items())


def static_vars(t):
    lines = []
    for k, v in t.get("font", {}).items():
        lines.append("--font-%s: %s;" % (k, v))
    for k, v in t.get("type", {}).items():
        lines.append("--text-%s: %s;" % (k, px(v["size"])))
        lines.append("--text-%s--line-height: %s;" % (k, px(v["line"])))
        lines.append("--text-%s--font-weight: %s;" % (k, v["weight"]))
    for i, v in enumerate(t.get("space", [])):
        lines.append("--space-%d: %s;" % (i, px(v)))
    for k, v in t.get("radius", {}).items():
        lines.append("--radius-%s: %s;" % (k, px(v)))
    for k, v in t.get("shadow", {}).items():
        lines.append("--shadow-%s: %s;" % (k, v))
    for k, v in t.get("motion", {}).items():
        lines.append("--motion-%s: %s;" % (k, v))
    for k, v in t.get("layout", {}).items():
        lines.append("--layout-%s: %s;" % (k, px(v)))
    glass = t.get("glass", {})
    if "blur" in glass:
        lines.append("--glass-blur: %s;" % px(glass["blur"]))
    if "saturate" in glass:
        lines.append("--glass-saturate: %s%%;" % glass["saturate"])
    return lines


def build_css(t, tailwind4=False):
    light = t.get("color", {})
    dark = t.get("color-dark", {})
    dark_first = t.get("theme-default") == "dark" and dark
    out = ["/* Generated by replica-design/build_tokens.py. Edit tokens.json, not this file. */", ""]
    if dark_first:
        # Dark is the product default whatever the OS says; light is an explicit toggle.
        full_dark = dict(light)
        full_dark.update(dark)
        out.append(":root {")
        out.append("  color-scheme: dark;")
        out.append(color_block(full_dark))
        out.extend("  " + l for l in static_vars(t))
        out.append("}")
        out += ["", ":root[data-theme=\"light\"] {", "  color-scheme: light;",
                color_block(light), "}"]
    else:
        out.append(":root {")
        out.append("  color-scheme: light;")
        out.append(color_block(light))
        out.extend("  " + l for l in static_vars(t))
        out.append("}")
    if dark and not dark_first:
        out += ["", "@media (prefers-color-scheme: dark) {",
                "  :root:not([data-theme=\"light\"]) {", "    color-scheme: dark;",
                color_block(dark, "    "), "  }", "}",
                "", ":root[data-theme=\"dark\"] {", "  color-scheme: dark;",
                color_block(dark), "}",
                "", ":root[data-theme=\"light\"] {", "  color-scheme: light;",
                color_block(light), "}"]
    # "type-ar", "type-he", …: per-language line heights and sizes under :lang(xx).
    for key in sorted(k for k in t if k.startswith("type-") and len(k) == 7):
        lang = key[5:]
        rows = []
        for k, v in t[key].items():
            if k.startswith("_"):
                continue
            rows.append("  --text-%s: %s;" % (k, px(v["size"])))
            rows.append("  --text-%s--line-height: %s;" % (k, px(v["line"])))
            rows.append("  --text-%s--font-weight: %s;" % (k, v["weight"]))
        out += ["", ":root:lang(%s), :lang(%s) {" % (lang, lang)] + rows + ["}"]
    if t.get("glass"):
        # Glass is opt-in per element (.glass); people who ask for less transparency get the solid surface.
        solid = t["glass"].get("fallback", "surface-raised")
        out += ["", "@media (prefers-reduced-transparency: reduce) {",
                # Same specificity as the theme blocks and later in the file, so it wins in every theme.
                "  :root, :root[data-theme=\"light\"], :root[data-theme=\"dark\"] {",
                "    --color-glass: var(--color-%s); --glass-blur: 0px; --glass-saturate: 100%%;" % solid,
                "  }", "}"]
    durations = [k for k in t.get("motion", {}) if k != "ease" and not k.startswith("ease")]
    if durations:
        out += ["", "@media (prefers-reduced-motion: reduce) {",
                "  :root { %s }" % " ".join("--motion-%s: 0ms;" % k for k in durations), "}"]
    if tailwind4:
        out += ["", "/* Tailwind v4: utilities read these. Values point at the runtime vars. */",
                "@theme inline {"]
        out += ["  --color-%s: var(--color-%s);" % (k, k) for k in light]
        out += ["  --font-%s: var(--font-%s);" % (k, k) for k in t.get("font", {})]
        for k in t.get("type", {}):
            out.append("  --text-%s: var(--text-%s);" % (k, k))
            out.append("  --text-%s--line-height: var(--text-%s--line-height);" % (k, k))
        out += ["  --radius-%s: var(--radius-%s);" % (k, k) for k in t.get("radius", {})]
        out += ["  --shadow-%s: var(--shadow-%s);" % (k, k) for k in t.get("shadow", {})]
        out.append("}")
    return "\n".join(out) + "\n"


def build_tailwind(t):
    ext = {
        "colors": {k: "var(--color-%s)" % k for k in t.get("color", {})},
        "fontFamily": {k: ["var(--font-%s)" % k] for k in t.get("font", {})},
        "fontSize": {k: ["var(--text-%s)" % k, {
            "lineHeight": "var(--text-%s--line-height)" % k,
            "fontWeight": "var(--text-%s--font-weight)" % k}] for k in t.get("type", {})},
        "spacing": {str(v // 4 if isinstance(v, int) and v % 4 == 0 else i): px(v)
                    for i, v in enumerate(t.get("space", []))},
        "borderRadius": {k: "var(--radius-%s)" % k for k in t.get("radius", {})},
        "boxShadow": {k: "var(--shadow-%s)" % k for k in t.get("shadow", {})},
        "transitionDuration": {k: "var(--motion-%s)" % k
                               for k in t.get("motion", {}) if not k.startswith("ease")},
        "maxWidth": {"content": "var(--layout-content-max)"} if "content-max" in t.get("layout", {}) else {},
    }
    colors = t.get("color", {})
    # Short aliases so `text-muted`, `text-subtle`, `border` and `ring` read naturally.
    ext["textColor"] = {k[5:]: "var(--color-%s)" % k for k in colors if k.startswith("text-")}
    if "text" in colors:
        ext["textColor"]["DEFAULT"] = "var(--color-text)"
    if "border" in colors:
        ext["borderColor"] = {"DEFAULT": "var(--color-border)"}
    if "focus" in colors:
        ext["ringColor"] = {"DEFAULT": "var(--color-focus)"}
    if "ease" in t.get("motion", {}):
        ext["transitionTimingFunction"] = {"DEFAULT": "var(--motion-ease)"}
    screens = {k: px(v) for k, v in t.get("breakpoints", {}).items()}
    theme = {"extend": {k: v for k, v in ext.items() if v}}
    if screens:
        theme["screens"] = screens
    # Tokens are CSS variables, so components rarely need `dark:`; when they do it must mean dark.
    if t.get("theme-default") == "dark":
        dark_mode = ["variant", ':root:not([data-theme="light"]) &']  # Tailwind >= 3.4.1
    else:
        dark_mode = ["selector", '[data-theme="dark"]']
    body = json.dumps({"darkMode": dark_mode, "theme": theme}, indent=2)
    return ("// Generated by replica-design/build_tokens.py. Edit tokens.json, not this file.\n"
            "// Spread into tailwind.config: module.exports = { ...require('./tailwind.tokens.js'), content: [...] }\n"
            "module.exports = %s;\n" % body)


def main(argv=None):
    ap = argparse.ArgumentParser(description="tokens.json -> tokens.css + Tailwind mapping")
    ap.add_argument("tokens")
    ap.add_argument("--out", help="output directory (default: next to tokens.json)")
    ap.add_argument("--tailwind4", action="store_true", help="emit @theme block instead of tailwind.tokens.js")
    ap.add_argument("--oklch", action="store_true", help="write colours as oklch() (hex kept in a comment)")
    a = ap.parse_args(argv)
    FORMAT["oklch"] = a.oklch
    try:
        with open(a.tokens, encoding="utf-8") as fh:
            t = json.load(fh)
    except (OSError, ValueError) as exc:
        print("build_tokens: %s" % exc, file=sys.stderr)
        return 2
    if not t.get("color"):
        print('build_tokens: tokens.json has no "color" block', file=sys.stderr)
        return 2
    out = a.out or os.path.dirname(os.path.abspath(a.tokens))
    os.makedirs(out, exist_ok=True)
    written = []
    path = os.path.join(out, "tokens.css")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(build_css(t, a.tailwind4))
    written.append(path)
    if not a.tailwind4:
        path = os.path.join(out, "tailwind.tokens.js")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(build_tailwind(t))
        written.append(path)
    for p in written:
        print("wrote %s" % p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
