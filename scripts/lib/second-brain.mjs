// Split a block of text into idea-sized pieces: Markdown bullets, numbered lines or paragraphs.
function splitIdeas(text) {
  const out = [];
  for (const block of String(text || "").split(/\n\s*\n/)) {
    const lines = block.split("\n").map(l => l.trim()).filter(Boolean);
    const bullets = lines.filter(l => /^([-*•]|\d+[.)])\s+/.test(l));
    if (bullets.length >= 2 || (bullets.length === 1 && lines.length === 1)) for (const l of bullets) out.push(l.replace(/^([-*•]|\d+[.)])\s+/, ""));
    else { const p = lines.filter(l => !/^#{1,6}\s/.test(l)).join(" "); if (p) out.push(p); }
  }
  return out.map(x => clean(x)).filter(x => x.length >= 4 && tokens(x).length >= 1);
}
// One list of raw ideas from everything the page could read. Each source is optional.
function gather(input) {
  const items = [], seen = new Set();
  const add = (src, text, at, ref) => {
    const t = clean(text);
    if (t.length < 4 || !tokens(t).length) return;
    const key = src + "|" + t;
    if (seen.has(key)) return;
    seen.add(key);
    items.push({ id: "i" + (items.length + 1), src, text: t, at: finite(at) ? at : 0, ref: ref || "" });
  };
  const i = input || {};
  for (const x of Array.isArray(i.own) ? i.own : []) if (x && typeof x.text === "string") add("own", x.text, +x.at, x.id ? "own:" + x.id : "");
  if (i.tradeNotes && typeof i.tradeNotes === "object") for (const [id, n] of Object.entries(i.tradeNotes)) {
    if (!n || typeof n !== "object") continue;
    if (n.lesson) add("tradeNote", n.lesson, +n.at, "trip:" + id);
    if (n.reason) add("tradeNote", n.reason, +n.at, "trip:" + id);
  }
  if (i.plan && typeof i.plan === "object") {
    for (const t of splitIdeas(i.plan.rules || "")) add("plan", t, 0, "plan:rules");
    for (const t of splitIdeas(i.plan.setups || "")) add("plan", t, 0, "plan:setups");
  }
  for (const x of Array.isArray(i.oracle) ? i.oracle : []) if (x && typeof x.q === "string") add("oracle", x.q, +x.at, "oracle:" + (x.mode === "intel" ? "intel" : "scholar"));
  if (i.chain && typeof i.chain === "object") for (const [ticker, md] of Object.entries(i.chain)) {
    if (typeof md !== "string") continue;
    // Only the person's own sections: the view in three sentences, what would prove it wrong, what changed.
    for (const title of ["رأيي في 3 جمل", "ما الذي قد يثبت خطئي", "ما الذي تغيّر"]) {
      const m = new RegExp(`^## ${title}\\s*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, "m").exec(md);
      if (m) for (const t of splitIdeas(m[1])) add("chain", `${ticker}: ${t}`, 0, "chain:" + ticker);
    }
  }
  // ADR-125: the open-source library joins as ideas when the page asks for it; its category words let the
  // clustering group it by what each tool would add.
  if (i.library === true) for (const x of LIBRARY) add("library", `${LIBRARY_CATS[x.cat].ar} · ${x.name}: ${x.ar} · ${LIBRARY_CATS[x.cat].en}, ${x.en} (${x.licence})`, 0, "lib:" + x.name);
  for (const f of Array.isArray(i.files) ? i.files : []) if (f && typeof f.text === "string") for (const t of splitIdeas(f.text).slice(0, 400)) add("file", t, +f.at, "file:" + clean(f.name || "", 80));
  return items.slice(0, 600);
}

/* ---------- vectors ---------- */
function vectorize(items) {
  const docs = items.map(x => tokens(x.text)), df = new Map(), N = docs.length;
  for (const d of docs) for (const t of new Set(d)) df.set(t, (df.get(t) || 0) + 1);
  const idf = t => Math.log((N + 1) / ((df.get(t) || 0) + 1)) + 1;
  return docs.map(d => {
    const tf = new Map();
    for (const t of d) tf.set(t, (tf.get(t) || 0) + 1);
    const v = new Map(); let norm = 0;
    for (const [t, c] of tf) { const w = (1 + Math.log(c)) * idf(t); v.set(t, w); norm += w * w; }
    norm = Math.sqrt(norm) || 1;
    for (const [t, w] of v) v.set(t, w / norm);
    return v;
  });
}
function cosine(a, b) {
  if (a.size > b.size) [a, b] = [b, a];
  let s = 0; for (const [t, w] of a) { const u = b.get(t); if (u) s += w * u; }
  return s;
}
function centroid(vs) {
  const c = new Map();
  for (const v of vs) for (const [t, w] of v) c.set(t, (c.get(t) || 0) + w / vs.length);
  let n = 0; for (const w of c.values()) n += w * w; n = Math.sqrt(n) || 1;
  for (const [t, w] of c) c.set(t, w / n);
  return c;
}

/* ---------- merge, cluster, rank ---------- */
// Near-duplicates (cosine ≥ thr) become one idea that remembers every source it came from.
function merge(items, thr = 0.8) {
  const vs = vectorize(items), parent = items.map((_, k) => k);
  const find = k => { while (parent[k] !== k) { parent[k] = parent[parent[k]]; k = parent[k]; } return k; };
  for (let a = 0; a < items.length; a++) for (let b = a + 1; b < items.length; b++) if (cosine(vs[a], vs[b]) >= thr) parent[find(b)] = find(a);
  const groups = new Map();
  items.forEach((x, k) => { const r = find(k); if (!groups.has(r)) groups.set(r, []); groups.get(r).push(k); });
  const ideas = [];
  for (const ks of groups.values()) {
    const members = ks.map(k => items[k]);
    // The text kept is the longest member; ties go to the newest.
    const lead = members.slice().sort((x, y) => y.text.length - x.text.length || y.at - x.at)[0];
    ideas.push({ id: "n" + (ideas.length + 1), text: lead.text, members, sources: [...new Set(members.map(m => m.src))], at: Math.max(...members.map(m => m.at)), merged: members.length });
  }
  return ideas;
}
// Average-linkage agglomerative clustering on cosine similarity; stops when no pair of clusters is closer than thr.
function cluster(vs, thr = 0.16) {
  let cl = vs.map((_, k) => [k]);
  const sim = vs.map((a, i) => vs.map((b, j) => i === j ? 1 : cosine(a, b)));
  for (;;) {
    let best = -1, bi = -1, bj = -1;
    for (let i = 0; i < cl.length; i++) for (let j = i + 1; j < cl.length; j++) {
      let s = 0; for (const a of cl[i]) for (const b of cl[j]) s += sim[a][b];
      s /= cl[i].length * cl[j].length;
      if (s > best) { best = s; bi = i; bj = j; }
    }
    if (bi < 0 || best < thr) break;
    cl[bi] = cl[bi].concat(cl[bj]); cl.splice(bj, 1);
  }
  return { clusters: cl, sim };
}
