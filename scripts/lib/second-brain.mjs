const AR_DIAC = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;
const AR_STOP = new Set("في من على الى إلى عن مع هذا هذه ذلك تلك التي الذي الذين ثم او أو و ف ب ل ك ما لا لم لن قد كل بعد قبل عند حتى اذا إذا ان أن إن كان كانت يكون هو هي هم نحن انا أنا انت أنت بين فوق تحت اي أي غير بس شي شيء ابي أبي ايش وش هل كيف لماذا ليش متى اين أين".split(" ").map(w => normAr(w)));
const EN_STOP = new Set("a an the and or but if of to in on at by for with from as is are was were be been being it its this that these those i you he she we they my your our their not no do does did so than then there here what which who whom how why when where can could should would will just about into over under more most very also".split(" "));

function normAr(w) {
  return String(w).replace(AR_DIAC, "").replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه").replace(/ؤ/g, "و").replace(/ئ/g, "ي");
}
// Light, rule-based stemming: Arabic leading conjunction and article, English plural and -ing. No dictionary.
function stemAr(w) {
  let t = w;
  for (const p of ["وال", "بال", "كال", "فال", "لل", "ال"]) if (t.startsWith(p) && t.length - p.length >= 3) { t = t.slice(p.length); break; }
  if (t.length >= 5 && (t.startsWith("و") || t.startsWith("ف"))) t = t.slice(1);
  for (const s of ["ات", "ون", "ين", "ها", "هم", "يه"]) if (t.endsWith(s) && t.length - s.length >= 3) { t = t.slice(0, -s.length); break; }
  return t;
}
function stemEn(w) {
  if (w.length > 5 && w.endsWith("ing")) return w.slice(0, -3);
  if (w.length > 4 && w.endsWith("ies")) return w.slice(0, -3) + "y";
  if (w.length > 4 && w.endsWith("s") && !w.endsWith("ss")) return w.slice(0, -1);
  return w;
}
function tokens(text) {
  const out = [];
  const raw = String(text || "").toLowerCase().replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x660)).split(/[^\p{L}\p{N}]+/u);
  for (const w0 of raw) {
    if (!w0) continue;
    if (/[؀-ۿ]/.test(w0)) {
      const w = normAr(w0);
      if (w.length < 2 || AR_STOP.has(w)) continue;
      const s = stemAr(w);
      if (s.length >= 2 && !AR_STOP.has(s)) out.push(s);
    } else if (/^[a-z][a-z0-9]*$/.test(w0)) {
      if (w0.length < 2 || EN_STOP.has(w0)) continue;
      out.push(stemEn(w0));
    } else if (/^\d{2,}$/.test(w0)) out.push(w0);
  }
  return out;
}
