// Second brain engine (ADR-119): pure functions shared by the second brain page (inlined between the OMEGA_BRAIN
// markers by scripts/build-brain-inline.mjs, because the page must work from file:// with no build step) and the
// Node tests (scripts/test-brain.mjs). No network, no storage, no clock except where a time is passed in.
//
// It gathers the ideas that already live in this browser (your own notes, TRADE LAB trade notes and plan rules,
// ORACLE questions, THE CHAIN's notes.md views) or in a text file you pick, and organises them with plain, checkable
// arithmetic: Arabic and English tokens, TF-IDF vectors, cosine similarity, near-duplicates merged into one idea,
// themes by average-linkage clustering, a rank from recency, links and source spread, and fixed rules that suggest
// how to develop each theme (ask ORACLE, test on paper in TRADE LAB, add evidence). Every grouping, name and rank
// is [INFERENCE]; nothing is generated by a language model and nothing leaves the browser.

const DAY = 86400000;
const finite = v => typeof v === "number" && Number.isFinite(v);

/* ---------- text ---------- */
const AR_DIAC = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;
const AR_STOP = new Set("في من على الى إلى عن مع هذا هذه ذلك تلك التي الذي الذين ثم او أو و ف ب ل ك ما لا لم لن قد كل بعد قبل عند حتى اذا إذا ان أن إن كان كانت يكون هو هي هم نحن انا أنا انت أنت بين فوق تحت اي أي غير بس شي شيء ابي أبي ايش وش هل كيف لماذا ليش متى اين أين".split(" ").map(w => normAr(w)));
const EN_STOP = new Set("a an the and or but if of to in on at by for with from as is are was were be been being it its this that these those i you he she we they my your our their not no do does did so than then there here what which who whom how why when where can could should would will just about into over under more most very also".split(" "));

function normAr(w) {
  return String(w).replace(AR_DIAC, "").replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه").replace(/ؤ/g, "و").replace(/ئ/g, "ي");
}
// Light, rule-based stemming: Arabic leading conjunction and article, English plural and -ing. No dictionary.
function stemAr(w) {
  let t = w;
  for (const p of ["وال", "بال", "كال", "فال", "لل", "ال"]) if (t.startsWith(p) && t.length - p.length >= 3) { t = t.slice(p.length); break; }
  if (t.length >= 5 && (t.startsWith("و") || t.startsWith("ف"))) t = t.slice(1);
  for (const s of ["ات", "ون", "ين", "ها", "هم", "يه"]) if (t.endsWith(s) && t.length - s.length >= 3) { t = t.slice(0, -s.length); break; }
  return t;
}
function stemEn(w) {
  if (w.length > 5 && w.endsWith("ing")) return w.slice(0, -3);
  if (w.length > 4 && w.endsWith("ies")) return w.slice(0, -3) + "y";
  if (w.length > 4 && w.endsWith("s") && !w.endsWith("ss")) return w.slice(0, -1);
  return w;
}
function tokens(text) {
  const out = [];
  const raw = String(text || "").toLowerCase().replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x660)).split(/[^\p{L}\p{N}]+/u);
  for (const w0 of raw) {
    if (!w0) continue;
    if (/[؀-ۿ]/.test(w0)) {
      const w = normAr(w0);
      if (w.length < 2 || AR_STOP.has(w)) continue;
      const s = stemAr(w);
      if (s.length >= 2 && !AR_STOP.has(s)) out.push(s);
    } else if (/^[a-z][a-z0-9]*$/.test(w0)) {
      if (w0.length < 2 || EN_STOP.has(w0)) continue;
      out.push(stemEn(w0));
    } else if (/^\d{2,}$/.test(w0)) out.push(w0);
  }
  return out;
}
const clean = (s, max = 600) => typeof s === "string" ? s.replace(/[\u0000-\u0008\u000B-\u001F\u007F]/g, "").replace(/\s+/g, " ").trim().slice(0, max) : "";

/* ---------- gathering ---------- */
const SOURCES = Object.freeze({
  own: { ar: "أفكاري", en: "My ideas" },
  tradeNote: { ar: "ملاحظات مختبر المتداول", en: "TRADE LAB notes" },
  plan: { ar: "خطة التداول", en: "Trading plan" },
  oracle: { ar: "أسئلة العرّاف", en: "ORACLE questions" },
  chain: { ar: "ملاحظات السلسلة", en: "THE CHAIN notes" },
  file: { ar: "ملف مستورد", en: "Imported file" }
});
// Split a block of text into idea-sized pieces: Markdown bullets, numbered lines or paragraphs.
function splitIdeas(text) {
  const out = [];
  for (const block of String(text || "").split(/\n\s*\n/)) {
    const lines = block.split("\n").map(l => l.trim()).filter(Boolean);
    const bullets = lines.filter(l => /^([-*•]|\d+[.)])\s+/.test(l));
    if (bullets.length >= 2 || (bullets.length === 1 && lines.length === 1)) for (const l of bullets) out.push(l.replace(/^([-*•]|\d+[.)])\s+/, ""));
    else { const p = lines.filter(l => !/^#{1,6}\s/.test(l)).join(" "); if (p) out.push(p); }
  }
  return out.map(x => clean(x)).filter(x => x.length >= 4 && tokens(x).length >= 1);
}
// One list of raw ideas from everything the page could read. Each source is optional.
function gather(input) {
  const items = [], seen = new Set();
  const add = (src, text, at, ref) => {
    const t = clean(text);
    if (t.length < 4 || !tokens(t).length) return;
    const key = src + "|" + t;
    if (seen.has(key)) return;
    seen.add(key);
    items.push({ id: "i" + (items.length + 1), src, text: t, at: finite(at) ? at : 0, ref: ref || "" });
  };
  const i = input || {};
  for (const x of Array.isArray(i.own) ? i.own : []) if (x && typeof x.text === "string") add("own", x.text, +x.at, x.id ? "own:" + x.id : "");
  if (i.tradeNotes && typeof i.tradeNotes === "object") for (const [id, n] of Object.entries(i.tradeNotes)) {
    if (!n || typeof n !== "object") continue;
    if (n.lesson) add("tradeNote", n.lesson, +n.at, "trip:" + id);
    if (n.reason) add("tradeNote", n.reason, +n.at, "trip:" + id);
  }
  if (i.plan && typeof i.plan === "object") {
    for (const t of splitIdeas(i.plan.rules || "")) add("plan", t, 0, "plan:rules");
    for (const t of splitIdeas(i.plan.setups || "")) add("plan", t, 0, "plan:setups");
  }
  for (const x of Array.isArray(i.oracle) ? i.oracle : []) if (x && typeof x.q === "string") add("oracle", x.q, +x.at, "oracle:" + (x.mode === "intel" ? "intel" : "scholar"));
  if (i.chain && typeof i.chain === "object") for (const [ticker, md] of Object.entries(i.chain)) {
    if (typeof md !== "string") continue;
    // Only the person's own sections: the view in three sentences, what would prove it wrong, what changed.
    for (const title of ["رأيي في 3 جمل", "ما الذي قد يثبت خطئي", "ما الذي تغيّر"]) {
      const m = new RegExp(`^## ${title}\\s*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, "m").exec(md);
      if (m) for (const t of splitIdeas(m[1])) add("chain", `${ticker}: ${t}`, 0, "chain:" + ticker);
    }
  }
  for (const f of Array.isArray(i.files) ? i.files : []) if (f && typeof f.text === "string") for (const t of splitIdeas(f.text).slice(0, 400)) add("file", t, +f.at, "file:" + clean(f.name || "", 80));
  return items.slice(0, 600);
}

/* ---------- vectors ---------- */
function vectorize(items) {
  const docs = items.map(x => tokens(x.text)), df = new Map(), N = docs.length;
  for (const d of docs) for (const t of new Set(d)) df.set(t, (df.get(t) || 0) + 1);
  const idf = t => Math.log((N + 1) / ((df.get(t) || 0) + 1)) + 1;
  return docs.map(d => {
    const tf = new Map();
    for (const t of d) tf.set(t, (tf.get(t) || 0) + 1);
    const v = new Map(); let norm = 0;
    for (const [t, c] of tf) { const w = (1 + Math.log(c)) * idf(t); v.set(t, w); norm += w * w; }
    norm = Math.sqrt(norm) || 1;
    for (const [t, w] of v) v.set(t, w / norm);
    return v;
  });
}
function cosine(a, b) {
  if (a.size > b.size) [a, b] = [b, a];
  let s = 0; for (const [t, w] of a) { const u = b.get(t); if (u) s += w * u; }
  return s;
}
function centroid(vs) {
  const c = new Map();
  for (const v of vs) for (const [t, w] of v) c.set(t, (c.get(t) || 0) + w / vs.length);
  let n = 0; for (const w of c.values()) n += w * w; n = Math.sqrt(n) || 1;
  for (const [t, w] of c) c.set(t, w / n);
  return c;
}

/* ---------- merge, cluster, rank ---------- */
// Near-duplicates (cosine ≥ thr) become one idea that remembers every source it came from.
function merge(items, thr = 0.8) {
  const vs = vectorize(items), parent = items.map((_, k) => k);
  const find = k => { while (parent[k] !== k) { parent[k] = parent[parent[k]]; k = parent[k]; } return k; };
  for (let a = 0; a < items.length; a++) for (let b = a + 1; b < items.length; b++) if (cosine(vs[a], vs[b]) >= thr) parent[find(b)] = find(a);
  const groups = new Map();
  items.forEach((x, k) => { const r = find(k); if (!groups.has(r)) groups.set(r, []); groups.get(r).push(k); });
  const ideas = [];
  for (const ks of groups.values()) {
    const members = ks.map(k => items[k]);
    // The text kept is the longest member; ties go to the newest.
    const lead = members.slice().sort((x, y) => y.text.length - x.text.length || y.at - x.at)[0];
    ideas.push({ id: "n" + (ideas.length + 1), text: lead.text, members, sources: [...new Set(members.map(m => m.src))], at: Math.max(...members.map(m => m.at)), merged: members.length });
  }
  return ideas;
}
// Average-linkage agglomerative clustering on cosine similarity; stops when no pair of clusters is closer than thr.
function cluster(vs, thr = 0.16) {
  let cl = vs.map((_, k) => [k]);
  const sim = vs.map((a, i) => vs.map((b, j) => i === j ? 1 : cosine(a, b)));
  for (;;) {
    let best = -1, bi = -1, bj = -1;
    for (let i = 0; i < cl.length; i++) for (let j = i + 1; j < cl.length; j++) {
      let s = 0; for (const a of cl[i]) for (const b of cl[j]) s += sim[a][b];
      s /= cl[i].length * cl[j].length;
      if (s > best) { best = s; bi = i; bj = j; }
    }
    if (bi < 0 || best < thr) break;
    cl[bi] = cl[bi].concat(cl[bj]); cl.splice(bj, 1);
  }
  return { clusters: cl, sim };
}
const TRADE_WORDS = new Set(tokens("صفقة صفقات تداول شراء بيع وقف ربح خسارة مخاطرة سوق شمعة دخول خروج trade trading buy sell stop loss profit risk market candle entry exit btc eth usdt rsi macd position"));
function topTerms(c, k = 3) { return [...c.entries()].sort((a, b) => b[1] - a[1]).slice(0, k).map(e => e[0]); }

// The whole pass: gather → merge → vectors → themes → rank → links → rules. `now` is passed in for recency.
function organise(input, opts = {}) {
  const now = finite(opts.now) ? opts.now : 0;
  const raw = gather(input);
  const ideas = merge(raw, finite(opts.mergeAt) ? opts.mergeAt : 0.8);
  const vs = vectorize(ideas);
  const { clusters, sim } = cluster(vs, finite(opts.themeAt) ? opts.themeAt : 0.16);
  const LINK = finite(opts.linkAt) ? opts.linkAt : 0.12;
  const links = [];
  for (let a = 0; a < ideas.length; a++) for (let b = a + 1; b < ideas.length; b++) if (sim[a][b] >= LINK) links.push({ a, b, w: sim[a][b] });
  const degree = ideas.map(() => 0); for (const l of links) { degree[l.a]++; degree[l.b]++; }
  const maxDeg = Math.max(1, ...degree);
  ideas.forEach((x, k) => {
    const age = now && x.at ? Math.max(0, (now - x.at) / DAY) : null;
    const recency = age == null ? 0.3 : Math.exp(-age / 30);
    x.degree = degree[k];
    x.score = Math.round(100 * (0.4 * recency + 0.35 * degree[k] / maxDeg + 0.25 * Math.min(1, (x.sources.length - 1 + Math.min(x.merged, 3) / 3) / 2)));
    x.question = /[?؟]\s*$/.test(x.text);
  });
  const themes = clusters.map((ks, t) => {
    const c = centroid(ks.map(k => vs[k])), terms = topTerms(c, 3);
    const label = terms.map(term => {
      // Show each term as it was written in the most common original word, not its stem.
      for (const k of ks) { const w = ideas[k].text.split(/[^\p{L}\p{N}]+/u).find(x => x && tokens(x)[0] === term); if (w) return w; }
      return term;
    });
    const members = ks.slice().sort((a, b) => ideas[b].score - ideas[a].score);
    const srcs = [...new Set(members.flatMap(k => ideas[k].sources))];
    const trade = members.some(k => tokens(ideas[k].text).some(w => TRADE_WORDS.has(w)));
    return { id: "t" + (t + 1), label, terms, members, sources: srcs, trade, size: members.length, score: Math.round(members.reduce((s, k) => s + ideas[k].score, 0) / members.length), question: members.some(k => ideas[k].question) };
  }).sort((a, b) => b.size - a.size || b.score - a.score);
  themes.forEach((th, i) => { th.id = "t" + (i + 1); for (const k of th.members) ideas[k].theme = i; });
  for (const th of themes) th.next = develop(th, ideas);
  return { raw: raw.length, ideas, themes, links, merged: raw.length - ideas.length };
}

// Fixed rules that say how to develop a theme. Each step names the rule that fired.
function develop(th, ideas) {
  const steps = [], q = th.label.join(" ");
  if (!th.sources.includes("oracle")) steps.push({ kind: "oracle", query: q, ar: `ابحث عنها في العرّاف: «${q}»`, en: `Research it in ORACLE: «${q}»`, rule: "no ORACLE question in this theme" });
  if (th.trade && !th.sources.includes("tradeNote")) steps.push({ kind: "tradelab", ar: "اختبرها على الورق في مختبر المتداول واكتب ملاحظة للصفقة", en: "Test it on paper in TRADE LAB and write a trade note", rule: "trading words, no trade note yet" });
  if (th.size === 1) steps.push({ kind: "evidence", ar: "فكرة منفردة: أضف سبباً أو دليلاً أو مثالاً يربطها بغيرها", en: "A lone idea: add a reason, evidence or an example that links it to others", rule: "theme of one idea" });
  if (th.sources.length >= 2) steps.push({ kind: "link", ar: `${th.sources.length} مصادر تلتقي هنا: اكتب الخلاصة في جملة واحدة`, en: `${th.sources.length} sources meet here: write the takeaway in one sentence`, rule: "two or more sources" });
  if (th.question) steps.push({ kind: "question", ar: "فيها سؤال مفتوح: حدّد ما الذي يجيب عنه", en: "It holds an open question: name what would answer it", rule: "idea ends with a question mark" });
  const dup = th.members.filter(k => ideas[k].merged > 1).length;
  if (dup) steps.push({ kind: "merged", ar: `دُمجت ${dup} فكرة مكررة؛ راجع النص المحفوظ`, en: `${dup} repeated ideas were merged; check the kept text`, rule: "near-duplicates merged" });
  return steps;
}

/* ---------- layout and export ---------- */
function mulberry32(seed) { let a = seed >>> 0; return () => { a = (a + 0x6d2b79f5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
// Seeded force layout in a unit square: the same ideas always land in the same places.
function layout(n, links, groups, seed = 119, iters = 220) {
  const rnd = mulberry32(seed), P = Array.from({ length: n }, (_, k) => ({ x: 0.5 + 0.35 * Math.cos((groups[k] || 0) * 2.4 + rnd()), y: 0.5 + 0.35 * Math.sin((groups[k] || 0) * 2.4 + rnd()) }));
  const k0 = 0.6 / Math.sqrt(Math.max(1, n));
  for (let it = 0; it < iters; it++) {
    const t = 0.08 * (1 - it / iters), D = P.map(() => ({ x: 0, y: 0 }));
    for (let a = 0; a < n; a++) for (let b = a + 1; b < n; b++) {
      const dx = P[a].x - P[b].x, dy = P[a].y - P[b].y, d = Math.max(1e-3, Math.hypot(dx, dy)), f = k0 * k0 / d * (groups[a] === groups[b] ? 0.6 : 1.2);
      D[a].x += dx / d * f; D[a].y += dy / d * f; D[b].x -= dx / d * f; D[b].y -= dy / d * f;
    }
    for (const l of links) {
      const dx = P[l.a].x - P[l.b].x, dy = P[l.a].y - P[l.b].y, d = Math.max(1e-3, Math.hypot(dx, dy)), f = d * d / k0 * l.w;
      D[l.a].x -= dx / d * f; D[l.a].y -= dy / d * f; D[l.b].x += dx / d * f; D[l.b].y += dy / d * f;
    }
    for (let a = 0; a < n; a++) {
      const m = Math.hypot(D[a].x, D[a].y) || 1, s = Math.min(m, t) / m;
      P[a].x = Math.min(0.97, Math.max(0.03, P[a].x + D[a].x * s + (0.5 - P[a].x) * 0.01));
      P[a].y = Math.min(0.97, Math.max(0.03, P[a].y + D[a].y * s + (0.5 - P[a].y) * 0.01));
    }
  }
  return P;
}
function toMarkdown(res, at) {
  const L = [`# المخ الثاني · Second brain`, "", `${at || ""} · ${res.ideas.length} فكرة من ${res.raw} مدخل، ${res.themes.length} محور، ${res.merged} مكرر مدموج. التجميع والأسماء والترتيب [INFERENCE] بقواعد ثابتة.`, ""];
  for (const th of res.themes) {
    L.push(`## ${th.label.join(" · ")}`, "");
    for (const k of th.members) { const x = res.ideas[k]; L.push(`- ${x.text} (${x.sources.map(s => SOURCES[s] ? SOURCES[s].ar : s).join("، ")} · ${x.score})`); }
    if (th.next.length) { L.push("", "**التطوير:**"); for (const s of th.next) L.push(`- ${s.ar}`); }
    L.push("");
  }
  return L.join("\n");
}

