/* ---------- text ---------- */
// The page passes the second brain's Arabic / English tokenizer (OMEGA_BRAIN.tokens) so both engines read words the
// same way; this fallback only lower-cases and splits.
const plainTokens = s => String(s || "").toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(w => w.length >= 2);
function bag(tok, text) { const m = new Map(); for (const t of tok(text)) m.set(t, (m.get(t) || 0) + 1); return m; }
function overlap(a, b) { let n = 0; for (const t of a.keys()) if (b.has(t)) n++; return n; }

/* ---------- decision records ---------- */
// Reads one ADR Markdown file into { n, title, status, refs, summary }. The build script runs it over docs/adr.
function parseAdr(md, fileName) {
  const text = String(md || "");
  const h = /^#\s*ADR-(\d{3})\s*[:·-]\s*(.+)$/m.exec(text);
  const n = h ? +h[1] : (/ADR-(\d{3})/.exec(String(fileName || "")) || [])[1];
  if (!finite(+n)) return null;
  const st = /status:\s*\**\s*([A-Za-z]+)/i.exec(text);
  const status = st ? st[1].toLowerCase() : "unknown";
  const refs = [...new Set((text.match(/ADR-(\d{3})/g) || []).map(x => +x.slice(4)).filter(x => x !== +n))].sort((a, b) => a - b);
  const ctx = /^##\s*Context\s*\n+([\s\S]*?)(?=\n\s*\n|\n##\s)/m.exec(text);
  const summary = clean((ctx ? ctx[1] : text.split(/\n\s*\n/).slice(1, 2).join(" ")).replace(/[*_`#>]/g, ""), 280);
  return { n: +n, title: clean(h ? h[2] : String(fileName || ""), 200), status: ["accepted", "proposed", "superseded", "rejected"].includes(status) ? status : "unknown", refs, summary, file: clean(String(fileName || ""), 120) };
}

/* ---------- graph ---------- */
// reg: { sources: {id: {name, terms, kind, home}}, library: [...], libraryCats: {...}, tools: {id: text},
//        helpers: [[id, en, ar]], adrs: [{n, title, status, refs, summary}] } (scripts/build-knowledge-inline.mjs)
// input: { brain: OMEGA_BRAIN.organise(...) result or null }
// opts: { tokens }
function build(reg, input = {}, opts = {}) {
  const tok = typeof opts.tokens === "function" ? opts.tokens : plainTokens;
  const nodes = [], edges = [], index = new Map(), seenEdge = new Set();
  const add = n => { if (index.has(n.id)) return index.get(n.id); n.ix = nodes.length; nodes.push(n); index.set(n.id, n.ix); return n.ix; };
  const link = (a, b, kind, w, extra) => {
    if (!index.has(a) || !index.has(b) || a === b) return;
    const key = a < b ? a + "|" + b : b + "|" + a;
    if (seenEdge.has(key)) return;
    seenEdge.add(key);
    edges.push({ a: index.get(a), b: index.get(b), kind, w: finite(w) ? w : (W[kind] || 0.5), ...(extra || {}) });
  };
  const domBags = DOMAINS.map(d => ({ d, bag: bag(tok, d.words + " " + d.en + " " + d.ar) }));
  // The strongest domains for a text: shared tokens, at least `min`, at most `top`, weight = hits / sqrt(tokens).
  const domainsFor = (text, top = 2, min = 1) => {
    const b = bag(tok, text), size = Math.sqrt(Math.max(1, b.size));
    return domBags.map(x => ({ id: x.d.id, hits: overlap(b, x.bag) })).filter(x => x.hits >= min)
      .sort((p, q) => q.hits - p.hits || DOMAINS.findIndex(d => d.id === p.id) - DOMAINS.findIndex(d => d.id === q.id)).slice(0, top)
      .map(x => ({ id: x.id, hits: x.hits, w: Math.min(1, x.hits / size + 0.15) }));
  };

  for (const d of DOMAINS) add({ id: "d:" + d.id, kind: "domain", ar: d.ar, en: d.en, text: d.words, ref: d.id });
  for (const p of PAGES) add({ id: "p:" + p.id, kind: "page", ar: p.ar, en: p.en, text: p.words.join(" ") + " " + p.en, ref: p.file });
  for (const d of DOMAINS) for (const p of d.pages) link("p:" + p, "d:" + d.id, "shows");

  add({ id: "a:lead", kind: "agent", ar: "PRIME القائد", en: "PRIME lead", text: "prime lead plan mission memory lessons recall note", ref: "lead" });
  link("a:lead", "p:ops", "runsOn"); link("a:lead", "p:core", "runsOn");
  for (const [id, en, ar] of Array.isArray(reg.helpers) ? reg.helpers : []) {
    const tool = HELPER_TOOL[id];
    add({ id: "a:" + id, kind: "agent", ar: clean(ar, 60), en: clean(en, 60), text: `${en} ${tool ? (reg.tools || {})[tool] || "" : "paper only, opens nothing from a plan"}`, ref: id, tool: tool || null });
    link("a:lead", "a:" + id, "leads");
    link("a:" + id, "p:ops", "runsOn");
  }
  for (const d of DOMAINS) for (const h of d.helpers) link("a:" + h, "d:" + d.id, "watches");

  for (const [id, s] of Object.entries(reg.sources || {})) {
    add({ id: "s:" + id, kind: "source", ar: clean(s.name, 80), en: clean(s.name, 80), text: `${s.name} ${s.kind} ${s.terms}`, ref: id, terms: clean(s.terms, 120), url: s.home, sub: s.kind });
    link("s:" + id, "p:oracle", "readBy");
  }
  for (const d of DOMAINS) for (const s of d.sources) link("s:" + s, "d:" + d.id, "feeds");

  const cats = Object.assign({}, reg.libraryCats || {}, KG_CAT);
  const tools = (Array.isArray(reg.library) ? reg.library : []).concat(KG_TOOLS);
  for (const t of tools) {
    const id = "t:" + t.name;
    add({ id, kind: "tool", ar: t.name, en: t.name, text: `${t.name} ${t.en} ${(cats[t.cat] || {}).en || ""}`, ref: t.cat, licence: clean(t.licence, 80), url: t.repo, status: t.status === "in use" ? "in use" : "idea", note: { ar: clean(t.ar, 200), en: clean(t.en, 200) }, sub: t.cat });
    for (const d of DOMAINS) if (d.lib.includes(t.cat)) link(id, "d:" + d.id, "serves");
  }

  const adrs = (Array.isArray(reg.adrs) ? reg.adrs : []).slice().sort((a, b) => a.n - b.n);
  for (const r of adrs) add({ id: "r:" + r.n, kind: "adr", ar: `ADR-${r.n}`, en: `ADR-${r.n}`, text: `${r.title} ${r.summary}`, ref: r.file, title: r.title, status: r.status, summary: r.summary });
  for (const r of adrs) {
    for (const x of r.refs || []) link("r:" + r.n, "r:" + x, "cites");
    const low = (r.title + " " + r.summary).toLowerCase();
    for (const p of PAGES) if (p.words.some(w => low.includes(w))) link("r:" + r.n, "p:" + p.id, "builds");
    for (const m of domainsFor(r.title + " " + r.summary, 2, 2)) link("r:" + r.n, "d:" + m.id, "about", m.w * 0.8, { hits: m.hits });
  }

  // Ideas and themes from the second brain (organise() output). Library ideas are skipped: tools are nodes already.
  const brain = input.brain && Array.isArray(input.brain.ideas) ? input.brain : null;
  if (brain) {
    const themeOf = new Map();
    (brain.themes || []).forEach((th, i) => {
      add({ id: "h:" + i, kind: "theme", ar: (th.label || []).join(" · "), en: (th.label || []).join(" · "), text: (th.label || []).join(" "), ref: th.id, size: th.size });
      for (const k of th.members || []) themeOf.set(k, i);
    });
    const names = tools.map(t => ({ id: "t:" + t.name, low: t.name.toLowerCase().replace(/\s*\(.*$/, "") })).filter(t => t.low.length >= 4);
    const srcNames = Object.entries(reg.sources || {}).map(([id, s]) => ({ id: "s:" + id, low: String(s.name || "").toLowerCase().replace(/\s*\(.*$/, "") })).filter(s => s.low.length >= 4);
    brain.ideas.forEach((x, k) => {
      if (!x || typeof x.text !== "string" || (x.sources || []).every(s => s === "library")) return;
      const id = "i:" + k;
      add({ id, kind: "idea", ar: clean(x.text, 160), en: clean(x.text, 160), text: x.text, ref: (x.sources || []).join(","), score: finite(x.score) ? x.score : 0, sources: x.sources || [] });
      if (themeOf.has(k)) link(id, "h:" + themeOf.get(k), "inTheme");
      for (const m of domainsFor(x.text, 2, 1)) link(id, "d:" + m.id, "about", m.w, { hits: m.hits });
      const low = x.text.toLowerCase();
      for (const t of names) if (low.includes(t.low)) link(id, t.id, "mentions");
      for (const s of srcNames) if (low.includes(s.low)) link(id, s.id, "mentions");
    });
    // A theme sits where its ideas point: one link to its strongest domain.
    (brain.themes || []).forEach((th, i) => {
      const m = domainsFor((th.label || []).join(" ") + " " + (th.members || []).map(k => (brain.ideas[k] || {}).text || "").join(" "), 1, 1)[0];
      if (m) link("h:" + i, "d:" + m.id, "about", m.w, { hits: m.hits });
    });
  }
  const adj = nodes.map(() => []);
  edges.forEach((e, k) => { adj[e.a].push(k); adj[e.b].push(k); });
  return { nodes, edges, adj, index };
}
const other = (e, i) => e.a === i ? e.b : e.a;
const neighbours = (g, i) => g.adj[i].map(k => other(g.edges[k], i));

/* ---------- ranking ---------- */
// Weighted PageRank on the undirected graph (power iteration). `personal` is an optional teleport vector: with it,
// this is personalised PageRank, the "where does attention flow from these seeds" score used by ask().
function pagerank(g, opt = {}) {
  const n = g.nodes.length, d = finite(opt.damping) ? opt.damping : 0.85, iters = opt.iters || 60;
  if (!n) return [];
  const strength = g.nodes.map((_, i) => g.adj[i].reduce((s, k) => s + g.edges[k].w, 0));
  let tele = opt.personal && opt.personal.length === n ? opt.personal.slice() : new Array(n).fill(1);
  const ts = tele.reduce((s, v) => s + v, 0) || 1; tele = tele.map(v => v / ts);
  let r = tele.slice();
  for (let it = 0; it < iters; it++) {
    const next = tele.map(v => (1 - d) * v);
    let dangling = 0;
    for (let i = 0; i < n; i++) {
      if (!strength[i]) { dangling += r[i]; continue; }
      for (const k of g.adj[i]) { const e = g.edges[k]; next[other(e, i)] += d * r[i] * e.w / strength[i]; }
    }
    for (let i = 0; i < n; i++) next[i] += d * dangling * tele[i];
    r = next;
  }
  return r;
}
// Brandes betweenness (unweighted shortest paths), normalised to 0..1. High values are bridges between worlds.
function betweenness(g) {
  const n = g.nodes.length, cb = new Array(n).fill(0);
  for (let s = 0; s < n; s++) {
    const S = [], P = Array.from({ length: n }, () => []), sigma = new Array(n).fill(0), dist = new Array(n).fill(-1);
    sigma[s] = 1; dist[s] = 0;
    const Q = [s];
    for (let h = 0; h < Q.length; h++) {
      const v = Q[h]; S.push(v);
      for (const w of neighbours(g, v)) {
        if (dist[w] < 0) { dist[w] = dist[v] + 1; Q.push(w); }
        if (dist[w] === dist[v] + 1) { sigma[w] += sigma[v]; P[w].push(v); }
      }
    }
    const delta = new Array(n).fill(0);
    while (S.length) { const w = S.pop(); for (const v of P[w]) delta[v] += sigma[v] / sigma[w] * (1 + delta[w]); if (w !== s) cb[w] += delta[w]; }
  }
  const norm = n > 2 ? (n - 1) * (n - 2) : 1;
  return cb.map(v => v / norm);
}
// Missing links (Adamic-Adar): pairs of nodes that are not linked but share neighbours, weighted by how rare each
// shared neighbour is. Only idea → tool, idea → source and idea → agent pairs are proposed, since those are the
// links a person can act on ("this idea could use this tool"). [INFERENCE]
function predict(g, k = 12) {
  const deg = g.nodes.map((_, i) => g.adj[i].length), out = [];
  const linked = new Set(g.edges.map(e => e.a < e.b ? e.a + "|" + e.b : e.b + "|" + e.a));
  const ideas = g.nodes.filter(x => x.kind === "idea").map(x => x.ix);
  const wanted = new Set(["tool", "source", "agent"]);
  for (const i of ideas) {
    const score = new Map();
    for (const z of neighbours(g, i)) {
      if (deg[z] < 2) continue;
      for (const j of neighbours(g, z)) {
        if (j === i || !wanted.has(g.nodes[j].kind)) continue;
        const key = i < j ? i + "|" + j : j + "|" + i;
        if (linked.has(key)) continue;
        const c = score.get(j) || { s: 0, via: [] };
        c.s += 1 / Math.log(deg[z] + 1); c.via.push(z);
        score.set(j, c);
      }
    }
    // Per idea, the best tool, source and agent; tools in use come first on ties.
    for (const kind of wanted) {
      const best = [...score.entries()].filter(([j]) => g.nodes[j].kind === kind)
        .sort((p, q) => q[1].s - p[1].s || (g.nodes[q[0]].status === "in use") - (g.nodes[p[0]].status === "in use") || p[0] - q[0])[0];
      if (best) out.push({ a: i, b: best[0], score: +best[1].s.toFixed(3), via: best[1].via.slice(0, 3) });
    }
  }
  return out.sort((p, q) => q.score - p.score || p.a - q.a || p.b - q.b).slice(0, k);
}

/* ---------- gaps ---------- */
// Fixed rules over each domain's neighbours. Each finding names the rule that fired.
function gaps(g) {
  const out = [];
  for (const d of DOMAINS) {
    const i = g.index.get("d:" + d.id), ns = neighbours(g, i).map(j => g.nodes[j]);
    const c = k => ns.filter(x => x.kind === k).length;
    const ideas = c("idea") + c("theme"), inUse = ns.filter(x => x.kind === "tool" && x.status === "in use").length;
    const row = { domain: d.id, ar: d.ar, en: d.en, ideas, tools: c("tool"), inUse, sources: c("source"), agents: c("agent"), adrs: c("adr"), findings: [] };
    if (ideas && !row.sources) row.findings.push({ level: "act", rule: "ideas but no open source", ar: "عندك أفكار هنا ولا مصدر مفتوح يغذيها: اقترح مصدراً مجانياً بلا مفتاح", en: "You have ideas here but no open source feeds them: propose a free keyless source" });
    if (ideas && !row.agents) row.findings.push({ level: "act", rule: "ideas but no agent", ar: "لا وكيل يراقب هذا المجال", en: "No agent watches this domain" });
    if (ideas && !inUse) row.findings.push({ level: "watch", rule: "ideas but no tool in use", ar: "كل الأدوات هنا أفكار فقط؛ اختر واحدة للمراجعة الأمنية", en: "Every tool here is an idea only; pick one for a security review" });
    if (ideas && !row.adrs) row.findings.push({ level: "watch", rule: "ideas but no decision", ar: "لم يُتخذ قرار مكتوب (ADR) في هذا المجال بعد", en: "No written decision (ADR) covers this domain yet" });
    if (!ideas && row.adrs >= 3) row.findings.push({ level: "ok", rule: "built, no idea yet", ar: `بُني في ${row.adrs} قرارات ولم تكتب فيه فكرة بعد`, en: `Built across ${row.adrs} decisions, and you have written no idea about it yet` });
    out.push(row);
  }
  const lone = g.nodes.filter(x => x.kind === "idea" && !neighbours(g, x.ix).some(j => g.nodes[j].kind === "domain")).map(x => x.ix);
  return { domains: out, lone };
}

/* ---------- ask ---------- */
// A question becomes a context pack: seeds are the nodes whose words overlap the question (share of the question's
// tokens they hold), personalised PageRank spreads from them, and the best nodes of each kind come back with the
// shortest path that links them to the strongest seed, so every answer says why it is there. [INFERENCE]
const PACK = Object.freeze({ domain: 3, idea: 5, tool: 5, source: 5, agent: 4, page: 3, adr: 5 });
function ask(g, question, opts = {}) {
  const tok = typeof opts.tokens === "function" ? opts.tokens : plainTokens;
  const q = bag(tok, clean(question, 400));
  if (!q.size || !g.nodes.length) return { ok: false, terms: [], seeds: [], groups: {}, domains: [] };
  const bags = opts.bags || g.nodes.map(x => bag(tok, `${x.en} ${x.ar} ${x.text || ""}`));
  const personal = g.nodes.map((x, i) => { const h = overlap(q, bags[i]); return h ? h / q.size * (x.kind === "domain" ? 1.5 : 1) : 0; });
  const seeds = personal.map((v, i) => [i, v]).filter(x => x[1] > 0).sort((a, b) => b[1] - a[1] || a[0] - b[0]);
  if (!seeds.length) return { ok: false, terms: [...q.keys()], seeds: [], groups: {}, domains: [] };
  const r = pagerank(g, { personal, iters: 40 });
  const base = opts.base || pagerank(g, { iters: 40 });
  // Lift over the plain rank, so hubs do not win every question.
  const lift = r.map((v, i) => v / (base[i] || 1e-9) * (personal[i] ? 2 : 1) * Math.sqrt(v));
  const top = seeds[0][0], groups = {};
  for (const [kind, k] of Object.entries(PACK)) {
    groups[kind] = g.nodes.filter(x => x.kind === kind).map(x => x.ix).sort((a, b) => lift[b] - lift[a] || a - b).slice(0, k)
      .filter(i => r[i] > 0).map(i => ({ i, score: +(lift[i] * 1e3).toFixed(3), seed: personal[i] > 0, path: path(g, top, i) }));
  }
  // The question's domains are the domains its words name; only when it names none do the spread's best ones count.
  const named = seeds.filter(([i]) => g.nodes[i].kind === "domain").slice(0, PACK.domain).map(([i]) => i);
  if (named.length) groups.domain = named.map(i => ({ i, score: +(lift[i] * 1e3).toFixed(3), seed: true, path: path(g, top, i) }));
  return { ok: true, terms: [...q.keys()], seeds: seeds.slice(0, 8).map(([i, v]) => ({ i, v: +v.toFixed(3) })), groups, domains: groups.domain.map(x => g.nodes[x.i].ref) };
}
// Shortest path by breadth-first search (ties go to the lower index, so it is deterministic).
function path(g, a, b, max = 6) {
  if (a === b) return [a];
  const prev = new Map([[a, -1]]), Q = [a];
  for (let h = 0; h < Q.length; h++) {
    const v = Q[h];
    for (const w of neighbours(g, v).sort((x, y) => x - y)) {
      if (prev.has(w)) continue;
      prev.set(w, v);
      if (w === b) { const out = [b]; let c = v; while (c !== -1) { out.unshift(c); c = prev.get(c); } return out.length - 1 <= max ? out : []; }
      Q.push(w);
    }
  }
  return [];
}

/* ---------- plan and the helpers' review ---------- */
// A draft from the pack (the tools of the agents it found), then each helper reviews it with one fixed rule and the
// fixes are applied in order. The result is a PRIME mission template; the page and the Ops Room check it again with
// OMEGA_CORE.checkPlan before it may run, so nothing here can name an order, a key or a money move.
const GEO = new Set(["geo", "sea", "cyber", "space", "news", "vision"]);
function plan(g, pack, goal) {
  const doms = new Set(pack && pack.domains || []);
  const trade = DOMAINS.some(d => d.trade && doms.has(d.id));
  const agents = (pack && pack.groups && pack.groups.agent || []).map(x => g.nodes[x.i]).filter(x => x && x.kind === "agent");
  const draft = [];
  const has = t => draft.some(s => s.tool === t);
  const push = (tool, after, why) => { if (!has(tool)) draft.push({ id: tool, tool, after: (after || []).filter(a => has(a)), why }); };
  for (const a of agents) if (a.tool) push(a.tool, [], `found by the question: ${a.en}`);
  const draftCopy = draft.map(s => ({ ...s, after: s.after.slice() }));
  const review = [];
  const say = (helper, ok, ar, en) => review.push({ helper, verdict: ok ? "ok" : "fix", ar, en });
  // 1. The lead: start from memory.
  if (!has("recall")) { draft.unshift({ id: "recall", tool: "recall", after: [], why: "recall what PRIME already learned on this" }); say("lead", false, "أضفت التذكّر أولاً: نبدأ مما تعلمناه", "Added recall first: start from what we learned"); }
  else say("lead", true, "التذكّر موجود", "Recall is there");
  // 2. The researcher: an ORACLE brief whenever open sources answer the question.
  const srcs = pack && pack.groups && pack.groups.source || [];
  if (srcs.length && !has("research")) { push("research", ["recall"], "prepare an ORACLE brief from the open sources found"); say("research", false, `أضفت بحث العرّاف: ${srcs.length} مصادر مفتوحة تجيب`, `Added an ORACLE brief: ${srcs.length} open sources answer`); }
  else say("research", true, srcs.length ? "البحث موجود" : "لا مصدر مفتوح في الحزمة", srcs.length ? "Research is there" : "No open source in the pack");
  // 3. The sentinel: the world picture for maps, seas, cyber, space, news and cameras.
  if ([...doms].some(d => GEO.has(d)) && !has("sentinel")) { push("sentinel", [], "read OSIRIS PWSI and the cyber and space index"); say("sentinel", false, "أضفت الحارس: السؤال يمس العالم أو السيبراني", "Added the sentinel: the question touches the world or cyber"); }
  else say("sentinel", true, "لا حاجة لإضافة", "Nothing to add");
  // 4. The auditor and the risk officer: any trading question checks the receipt chain and ends at the risk gate.
  if (trade) {
    if (!has("audit")) { draft.push({ id: "audit", tool: "audit", after: [], why: "re-verify the receipt chain before any reading of the desk" }); say("audit", false, "أضفت التدقيق: سؤال تداول يبدأ بسلسلة فواتير سليمة", "Added the audit: a trading question starts from a sound receipt chain"); }
    else say("audit", true, "التدقيق موجود", "The audit is there");
    const before = draft.filter(s => ["scout", "analyst", "quant", "audit", "sentinel"].includes(s.tool)).map(s => s.id);
    const r = draft.find(s => s.tool === "risk");
    if (!r) { draft.push({ id: "risk", tool: "risk", after: before, why: "check the risk gate and the court's veto line; it can only stop" }); say("risk", false, "أضفت بوابة المخاطر بعد كل قراءة للسوق: ورقي فقط، ويمكنها الإيقاف فقط", "Added the risk gate after every market reading: paper only, it can only stop"); }
    else { r.after = [...new Set(r.after.concat(before.filter(x => x !== r.id)))]; say("risk", true, "بوابة المخاطر تنتظر كل القراءات", "The risk gate waits for every reading"); }
  } else say("risk", true, "ليس سؤال تداول", "Not a trading question");
  // 5. The paper executor never acts from a plan.
  say("exec", true, "المنفذ الورقي لا يفتح صفقة من خطة؛ فقط على OPEN من حكم المخاطر", "The paper executor opens nothing from a plan; only on the risk judge's OPEN");
  // 6. The organizer: recall first, note last waiting for everything, at most 12 steps.
  for (const s of draft) if (s.tool !== "recall" && !s.after.length && s.tool !== "audit" && s.tool !== "sentinel") s.after = ["recall"];
  const body = draft.filter(s => s.tool !== "note").slice(0, 11);
  body.push({ id: "note", tool: "note", after: body.map(s => s.id), why: "write the mission's summary into the journal and memory" });
  const valid = new Set(body.map(s => s.id));
  for (const s of body) s.after = s.after.filter(a => valid.has(a) && a !== s.id);
  say("ops", body.length <= 12, `الخطة ${body.length} خطوات، تبدأ بالتذكّر وتنتهي بالملاحظة`, `The plan has ${body.length} steps, starting with recall and ending with the note`);
  const names = DOMAINS.filter(d => doms.has(d.id)).map(d => d.en).join(", ") || "general";
  const g0 = clean(goal, 200) || `Knowledge mission on ${names}`;
  return { draft: draftCopy, review, trade, plan: { id: "know", en: "Knowledge mission", ar: "مهمة المعرفة", goal: g0, steps: body.map(s => ({ id: s.id, tool: s.tool, after: s.after, why: clean(s.why, 160) })) } };
}

/* ---------- design brief ---------- */
// What to build on, what to read, what to consider and what is still open, from the pack and the gaps. [INFERENCE]
function brief(g, pack, gapRes) {
  const pick = kind => (pack && pack.groups && pack.groups[kind] || []).map(x => g.nodes[x.i]);
  const doms = new Set(pack && pack.domains || []);
  const open = (gapRes ? gapRes.domains : []).filter(d => doms.has(d.domain)).flatMap(d => d.findings.filter(f => f.level !== "ok").map(f => ({ domain: d.domain, ...f })));
  return {
    page: pick("page")[0] || null,
    read: pick("source").map(s => ({ id: s.ref, name: s.en, terms: s.terms })),
    consider: pick("tool").map(t => ({ name: t.en, licence: t.licence, status: t.status, url: t.url })),
    decisions: pick("adr").map(r => ({ n: r.ref, title: r.title, status: r.status })),
    ideas: pick("idea").map(x => x.en),
    open
  };
}

/* ---------- layout ---------- */
function hash(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return (h >>> 0) / 4294967296; }
// Radial and deterministic: domains on a ring, pages and agents inside it, every other node at the circular mean
// of its domains' angles in its own band (ideas and themes inside, tools and sources outside, decisions as the
// outer belt). Nodes with no domain sit on the edge. Returns unit coordinates around (0, 0), radius ≤ 0.5.
const BAND = Object.freeze({ page: 0.1, agent: 0.19, theme: 0.25, idea: 0.29, domain: 0.36, tool: 0.41, source: 0.45, adr: 0.48 });
function layout(g) {
  const P = new Array(g.nodes.length), ang = new Map();
  DOMAINS.forEach((d, k) => { const a = -Math.PI / 2 + k * 2 * Math.PI / DOMAINS.length; ang.set(g.index.get("d:" + d.id), a); });
  const fixedRing = (kind, r) => { const xs = g.nodes.filter(x => x.kind === kind); xs.forEach((x, k) => { const a = -Math.PI / 2 + (k + 0.5) * 2 * Math.PI / xs.length; P[x.ix] = { x: r * Math.cos(a), y: r * Math.sin(a), a }; }); };
  for (const [i, a] of ang) P[i] = { x: BAND.domain * Math.cos(a), y: BAND.domain * Math.sin(a), a };
  fixedRing("page", BAND.page); fixedRing("agent", BAND.agent);
  for (const x of g.nodes) {
    if (P[x.ix]) continue;
    const ds = neighbours(g, x.ix).filter(j => ang.has(j));
    let a, r = BAND[x.kind] || 0.45;
    const j = hash(x.id) - 0.5;
    if (ds.length) {
      let sx = 0, sy = 0; for (const d of ds) { sx += Math.cos(ang.get(d)); sy += Math.sin(ang.get(d)); }
      a = Math.atan2(sy, sx) + j * (2 * Math.PI / DOMAINS.length) * 0.8;
      if (Math.hypot(sx, sy) < 0.2 * ds.length) r *= 0.75;
      r += (hash(x.id + "r") - 0.5) * 0.035;
    } else { a = j * 2 * Math.PI; r = 0.495; }
    P[x.ix] = { x: r * Math.cos(a), y: r * Math.sin(a), a };
  }
  return P;
}

/* ---------- enrichment (optional, the page asks first) ---------- */
// Wikidata entity search (CC0) and OpenAlex topics (CC0), both keyless with browser CORS. Only these two paths are
// ever built or accepted, over https, with no user name, port or fragment.
const ENRICH = Object.freeze({ wikidata: [/^www\.wikidata\.org$/, "/w/api.php"], openalex: [/^api\.openalex\.org$/, "/topics"] });
function enrichUrls(domainId, lang = "en") {
  const d = DOMAINS.find(x => x.id === domainId);
  if (!d) return null;
  const q = encodeURIComponent(d.q), l = lang === "ar" ? "ar" : "en";
  return {
    wikidata: `https://www.wikidata.org/w/api.php?action=wbsearchentities&search=${q}&language=en&uselang=${l}&type=item&limit=3&format=json&origin=*`,
    openalex: `https://api.openalex.org/topics?search=${q}&per-page=3`
  };
}
function allowedEnrich(source, url) {
  const e = Object.prototype.hasOwnProperty.call(ENRICH, source) ? ENRICH[source] : null;
  if (!e || typeof url !== "string" || url.length > 600) return false;
  try { const u = new URL(url); return u.protocol === "https:" && e[0].test(u.hostname) && u.pathname === e[1] && !u.username && !u.password && !u.port && !u.hash; } catch { return false; }
}
