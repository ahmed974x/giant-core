// One Markdown file in the Obsidian / Foam style: a heading per domain with [[links]] to everything around it.
function toMarkdown(g, at, rank) {
  const name = x => (x.kind === "adr" ? `${x.en} ${x.title || ""}` : x.en).replace(/[[\]|]/g, " ").trim();
  const L = [`# نطاق المعرفة · Knowledge domain`, "", `${at || ""} · ${g.nodes.length} عقدة، ${g.edges.length} رابط. الروابط من الكلمات والترتيب والتوقعات [INFERENCE]. Links from words, ranks and predictions are [INFERENCE].`, ""];
  for (const d of DOMAINS) {
    const i = g.index.get("d:" + d.id);
    L.push(`## ${d.ar} · ${d.en}`, "");
    const by = {};
    for (const k of g.adj[i]) { const e = g.edges[k], j = other(e, i), x = g.nodes[j]; (by[x.kind] = by[x.kind] || []).push([x, e]); }
    for (const kind of Object.keys(KINDS)) {
      if (!by[kind]) continue;
      const xs = by[kind].sort((p, q) => (rank ? rank[q[0].ix] - rank[p[0].ix] : 0) || p[0].ix - q[0].ix);
      L.push(`- **${KINDS[kind].en}:** ${xs.map(([x, e]) => `[[${name(x)}]]${e.kind === "about" ? " [INFERENCE]" : ""}`).join(", ")}`);
    }
    L.push("");
  }
  return L.join("\n");
}
function toJSON(g, at, extra) {
  return { format: "omega-knowledge-graph-v1", exported: at || null, nodes: g.nodes.map(x => ({ id: x.id, kind: x.kind, ar: x.ar, en: x.en, ref: x.ref, status: x.status || null, licence: x.licence || null, terms: x.terms || null, url: x.url || null })),
    edges: g.edges.map(e => ({ a: g.nodes[e.a].id, b: g.nodes[e.b].id, kind: e.kind, w: +e.w.toFixed(3) })), ...(extra || {}) };
}

