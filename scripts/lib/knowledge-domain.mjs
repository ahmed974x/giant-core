// context pack (personalised PageRank from the words of the question, with the path that explains each answer),
// drafts a paper-only PRIME plan from that pack and has the helpers review and correct it. Every ranking, link
// from words, prediction and plan is [INFERENCE]; nothing is generated by a language model.

