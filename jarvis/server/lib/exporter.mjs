// Studio 5-in-1 exporter (ADR-145), pure: inlined into the page, tested by the server tests. From one Studio
// site it writes four texts; the fifth, the standalone HTML page, is the Studio's existing download with its
// strict CSP. Nothing here runs the code it writes, sends anything or reads the network.
//   1. exportComponent: a zero-dependency Web Component (.mjs) with Shadow DOM. Text goes in with
//      textContent only; the lang attribute switches Arabic (right to left) and English.
//   2. exportTokens: W3C design tokens (.tokens.json, DTCG format) with the contrast of each text pair.
//   3. exportSql: a PostgreSQL schema inferred from the sections [INFERENCE]. Payments, publishing and
//      permission tables start at pending_approval and a check refuses "approved" without a person and a
//      time, so no row can stand for money moved, a page published or access granted by itself (AGENTS.md §1).
//   4. exportSpec: a Playwright test that opens the HTML at 390 × 844, 1440 × 900 and 2560 × 1080, light and
//      dark, and fails on a console error or a horizontal scroll.
export const slugOf = s => String(s || "site").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "site";
const ident = s => slugOf(s).replace(/-/g, "_").replace(/^(\d)/, "t_$1") || "t";
const sqlText = s => "'" + String(s).replace(/'/g, "''").slice(0, 200) + "'";
const allText = site => (site.blocks || []).flatMap(b => Object.values(b.t || {}).flatMap(t => Object.values(t || {}))).join(" ");

export function exportTokens(site, contrast) {
  const th = site.theme || {};
  const color = {};
  for (const k of ["bg", "surface", "text", "muted", "accent", "onAccent", "border"]) if (/^#[0-9a-f]{6}$/i.test(th[k] || "")) color[k] = { $type: "color", $value: th[k].toLowerCase() };
  const pairs = [["text", "bg"], ["muted", "bg"], ["text", "surface"], ["muted", "surface"], ["onAccent", "accent"], ["accent", "bg"]];
  const checks = pairs.filter(([f, b]) => color[f] && color[b]).map(([f, b]) => {
    const c = contrast ? contrast(color[f].$value, color[b].$value) : null;
    return { fg: f, bg: b, ratio: c ? Math.round(c.ratio * 100) / 100 : null, apcaLc: c ? Math.round(Math.abs(c.apca)) : null, pass: c ? c.ratio >= 4.5 && Math.abs(c.apca) >= 60 : null };
  });
  return {
    color,
    font: {
      sans: { $type: "fontFamily", $value: ["Inter Variable", "Readex Pro Variable", "system-ui", "sans-serif"] },
      arabic: { $type: "fontFamily", $value: ["Readex Pro Variable", "Inter Variable", "Tahoma", "sans-serif"] },
    },
    radius: { card: { $type: "dimension", $value: "20px" }, control: { $type: "dimension", $value: "12px" } },
    $extensions: { "jarvis.site": { name: String(site.name || ""), lang: site.lang === "ar" ? "ar" : "en", generatedBy: "Jarvis Studio (ADR-145)" }, "jarvis.contrast": { rule: "WCAG >= 4.5 and APCA Lc >= 60", checks } },
  };
}

export function exportSql(site) {
  const text = allText(site) + " " + (site.name || "");
  const out = ["-- Schema inferred from the Studio site " + sqlText(site.name || "site") + " [INFERENCE]. PostgreSQL 16. Generated by Jarvis Studio (ADR-145).",
    "-- Review it before use. Tables that stand for money, publishing or access start at pending_approval;",
    "-- a check refuses \"approved\" without a person and a time (AGENTS.md section 1).", "",
    "create table site_sections (\n  id text primary key,\n  type text not null,\n  position integer not null check (position >= 0),\n  visible boolean not null default true\n);"];
  const tables = ["site_sections"], locked = [];
  const types = new Set((site.blocks || []).filter(b => b.on !== false).map(b => b.type));
  if (types.has("faq")) { tables.push("faq_items"); out.push("create table faq_items (\n  id bigint generated always as identity primary key,\n  question text not null check (length(question) between 1 and 300),\n  answer text not null,\n  lang text not null check (lang in ('ar', 'en')),\n  position integer not null default 0\n);"); }
  if (types.has("features")) { tables.push("features"); out.push("create table features (\n  id bigint generated always as identity primary key,\n  title text not null,\n  body text not null default '',\n  lang text not null check (lang in ('ar', 'en'))\n);"); }
  if (types.has("stats")) { tables.push("facts"); out.push("create table facts (\n  id bigint generated always as identity primary key,\n  value text not null,\n  label text not null,\n  source text not null,          -- every figure names its source (AGENTS.md section 3)\n  checked_at date not null\n);"); }
  for (const b of (site.blocks || []).filter(x => x.type === "table" && x.on !== false)) {
    const t = (b.t && (b.t.en || b.t.ar)) || {};
    const cols = [1, 2, 3, 4, 5, 6].map(i => t["c" + i]).filter(Boolean).map(ident).filter((c, i, a) => a.indexOf(c) === i);
    const name = "table_" + ident(t.title || b.id);
    tables.push(name);
    out.push("create table " + name + " (\n  id bigint generated always as identity primary key" + cols.map(c => ",\n  " + c + " text").join("") + "\n);");
  }
  if (types.has("cta") || types.has("hero") || types.has("nav")) { tables.push("leads"); out.push("create table leads (\n  id bigint generated always as identity primary key,\n  email text not null check (email ~ '^[^@\\s]+@[^@\\s]+$'),\n  consent boolean not null check (consent),  -- stored only with consent\n  created_at timestamptz not null default now()\n);"); }
  const lockedTable = (name, extra, why) => {
    tables.push(name); locked.push(name);
    out.push("-- " + why + "\ncreate table " + name + " (\n  id bigint generated always as identity primary key," + extra + "\n  status text not null default 'pending_approval' check (status in ('pending_approval', 'approved', 'rejected')),\n  approved_by text,\n  approved_at timestamptz,\n  created_at timestamptz not null default now(),\n  constraint " + name + "_locked check (status <> 'approved' or (approved_by is not null and approved_at is not null))\n);");
  };
  if (/\b(price|pricing|plans?|subscri\w*|pay\w*|checkout|billing|invoice)\b|[$€£]|سعر|أسعار|اشتراك|ادفع|دفع|فاتورة/i.test(text)) lockedTable("payments", "\n  amount_minor bigint not null check (amount_minor > 0),\n  currency char(3) not null,", "Money: a row is a request. Nothing here moves money; approving it is Director 00's locked decision.");
  lockedTable("publish_requests", "\n  target text not null,", "Publishing: the site goes out only after a person approves.");
  if (/\b(team|members?|admins?|roles?|invite|permissions?|access)\b|فريق|عضو|أعضاء|صلاحي/i.test(text)) lockedTable("permission_grants", "\n  member text not null,\n  role text not null check (role in ('viewer', 'editor', 'admin')),", "Permissions: access is granted only after a person approves.");
  return { sql: out.join("\n\n") + "\n", tables, locked };
}

export function exportComponent(site, css) {
  const tag = "jarvis-" + slugOf(site.name);
  const data = JSON.stringify({ name: site.name, lang: site.lang, theme: site.theme, blocks: (site.blocks || []).filter(b => b.on !== false).slice(0, 20).map(b => ({ type: b.type, t: b.t })) }).replace(/</g, "\\u003c");
  const shadowCss = String(css || "").replace(/:root/g, ":host").replace(/(^|[\s,}])body(?=[\s,{.:])/g, "$1:host");
  return `// <${tag}>: the Studio site "${String(site.name || "site").replace(/[`$\\]/g, "")}" as a Web Component. Zero dependencies; Shadow DOM.
// Generated by Jarvis Studio (ADR-145). Text goes in with textContent only. <${tag} lang="ar"> shows Arabic, right to left.
//   Load ./${slugOf(site.name)}.mjs as a module script, then write <${tag}></${tag}> in the page.
const DATA = ${data};
const CSS = ${JSON.stringify(shadowCss)};
const VARS = { bg: "--bg", surface: "--surface", text: "--text", muted: "--muted", accent: "--accent", onAccent: "--on-accent", border: "--border" };
const el = (tag, cls, text) => { const n = document.createElement(tag); if (cls) n.className = cls; if (text) n.textContent = String(text).slice(0, 400); return n; };
const link = (text, cls) => { const a = el("a", cls, text); a.href = "#"; return a; };
function section(type, t) {
  const s = el(type === "nav" ? "header" : type === "footer" ? "footer" : "section", type), w = el("div", "wrap");
  s.append(w);
  if (t.brand) w.append(el("span", "brand", t.brand));
  if (t.kicker) w.append(el("p", "kicker", t.kicker));
  if (t.title) w.append(el(type === "hero" ? "h1" : "h2", null, t.title));
  if (t.body || t.text) w.append(el("p", null, t.body || t.text));
  if (t.links) { const ul = el("ul", "links"); String(t.links).split(/[,،]/).map(x => x.trim()).filter(Boolean).slice(0, 7).forEach(x => { const li = el("li"); li.append(link(x)); ul.append(li); }); w.append(ul); }
  const grid = el("div", "grid");
  for (let i = 1; i <= 6; i++) {
    if (t["f" + i + "t"]) { const c = el("div", "card"); c.append(el("h3", null, t["f" + i + "t"]), el("p", null, t["f" + i + "b"] || "")); grid.append(c); }
    if (t["s" + i + "v"]) { const c = el("div", "stat"); c.append(el("b", null, t["s" + i + "v"]), el("span", null, t["s" + i + "l"] || "")); grid.append(c); }
    if (t["q" + i]) { const d = el("details"); d.append(el("summary", null, t["q" + i]), el("p", null, t["a" + i] || "")); w.append(d); }
  }
  if (grid.childElementCount) w.append(grid);
  const acts = el("div", "actions");
  for (const k of ["primary", "secondary", "button", "cta"]) if (t[k]) acts.append(link(t[k], "btn " + (k === "secondary" ? "ghost" : "primary")));
  if (acts.childElementCount) w.append(acts);
  return s;
}
class JarvisSite extends HTMLElement {
  static get observedAttributes() { return ["lang"]; }
  connectedCallback() { this.render(); }
  attributeChangedCallback() { if (this.shadowRoot) this.render(); }
  render() {
    const root = this.shadowRoot || this.attachShadow({ mode: "open" });
    const lang = (this.getAttribute("lang") || DATA.lang) === "ar" ? "ar" : "en";
    this.dir = lang === "ar" ? "rtl" : "ltr";
    for (const [k, v] of Object.entries(VARS)) if (/^#[0-9a-f]{6}$/i.test((DATA.theme || {})[k] || "")) this.style.setProperty(v, DATA.theme[k]);
    const style = el("style");
    style.textContent = CSS;
    root.replaceChildren(style, ...DATA.blocks.map(b => section(b.type, (b.t && b.t[lang]) || {})));
  }
}
// The page's build strips "export" at the start of a line, so the default export shares this line.
if (!customElements.get("${tag}")) customElements.define("${tag}", JarvisSite); export default JarvisSite;
`;
}

export function exportSpec(site) {
  const name = slugOf(site.name);
  return `// Three sizes x light/dark for ${name}.html, written by Jarvis Studio (ADR-145) after DESIGN.md section 5.
// Put it next to the exported page, then: npx playwright test ${name}.spec.mjs
import { test, expect } from "@playwright/test";

const PAGE = new URL("./${name}.html", import.meta.url).href;
const SIZES = [["mobile", { width: 390, height: 844 }, 3], ["laptop", { width: 1440, height: 900 }, 1], ["ultra-wide", { width: 2560, height: 1080 }, 1]];

for (const [size, viewport, deviceScaleFactor] of SIZES) for (const colorScheme of ["light", "dark"]) {
  test(\`${name} at \${size} \${colorScheme}\`, async ({ browser }) => {
    const ctx = await browser.newContext({ viewport, deviceScaleFactor, colorScheme });
    const page = await ctx.newPage();
    const errors = [];
    page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(PAGE);
    await expect(page.locator("h1").first()).toBeVisible();
    const wide = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
    expect(wide, "no horizontal page scroll").toBe(false);
    expect(errors, "no console or page errors").toEqual([]);
    await ctx.close();
  });
}
`;
}
